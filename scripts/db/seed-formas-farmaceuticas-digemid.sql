CREATE FUNCTION pg_temp.clave_forma(text) RETURNS text
LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT regexp_replace(translate(lower($1), 'áéíóúüñ', 'aeiouun'), '[^a-z0-9]', '', 'g')
$$;
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM sch_catalogo.forma_farmaceutica f JOIN formas_carga s
          ON f.codigo = s.codigo OR pg_temp.clave_forma(f.denominacion) = pg_temp.clave_forma(s.denominacion)
        WHERE f.codigo <> s.codigo
           OR pg_temp.clave_forma(f.denominacion) <> pg_temp.clave_forma(s.denominacion)
           OR f.estado <> 'ACTIVO' OR f.es_activo <> '1'
    ) THEN
        RAISE EXCEPTION 'Forma existente con codigo, denominacion o estado incompatible; revisar antes de cargar.';
    END IF;
END $$;

WITH nuevas AS (
    INSERT INTO sch_catalogo.forma_farmaceutica (codigo, denominacion, fuente)
    SELECT codigo, denominacion,
           'DIGEMID ST_FFD Agosto 2026 V.01 | https://www.digemid.minsa.gob.pe/Archivos/PortalWeb/Informativo/Catalogacion/CAT_FORMAS_FARMACEUTICAS_DETALLADAS_2026.pdf'
    FROM formas_carga
    ON CONFLICT (codigo) DO NOTHING
    RETURNING codigo
)
SELECT count(*) AS formas_insertadas FROM nuevas;

DO $$
BEGIN
    IF (SELECT count(*) FROM sch_catalogo.forma_farmaceutica f JOIN formas_carga s USING (codigo)
        WHERE f.denominacion = s.denominacion AND f.estado = 'ACTIVO' AND f.es_activo = '1') <> 220 THEN
        RAISE EXCEPTION 'No se verificaron las 220 formas esperadas';
    END IF;
END $$;
COMMIT;

SELECT count(*) AS total_formas,
       count(*) FILTER (WHERE estado = 'ACTIVO' AND es_activo = '1') AS activas
FROM sch_catalogo.forma_farmaceutica;

